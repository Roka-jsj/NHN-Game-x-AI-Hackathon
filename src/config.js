// 증거: 예전 값표에서 배수를 1.0 → 3.0 까지 쓸어도 동일 금액 6×6(30쌍) 대진표가
//   **한 쌍도 안 바뀐다(0/30).** 금당 효율 격차가 6.80배라 1.75배든 3배든
//   그 앞에서 전부 삼켜졌다. 배수는 문자 그대로 장식이었다.
// 가격을 전투력에 맞춘 지금은 효율 격차가 1.04배다. 같은 스윕을 다시 하면
//   **2/30 이 바뀐다** (상성 6쌍 중 2쌍). 그리고 격차 하네스(80판)가 이렇게 답한다:
 //   (근접 추월 패치 이전 트리에서 잰 값: 1.75 → 2%p · 2.5 → 18%p · 3.5 → 26%p)
// **그런데 값을 이걸로 고른 게 아니다.** 근접이 원거리를 추월하게 된 뒤(4b35ce4)
// 다시 재 보니 배수는 격차를 거의 안 움직인다(1.75 → −15%p · 2.5 → −2%p · 3.5 → +3%p,
// 80판 표본). 그 자리에서 배수를 고르는 기준이 하나 남았다 — **삼각형이다**:
//     배수 1.75 → 삼각형 동수 **4/6** (깨진다)   배수 2.5·3.0·3.5 → 동수 6/6
//   이 값표는 투석기가 두꺼워져(46→118) 예전 배수로는 상성이 안 도는 변이 생겼다.
//   그래서 **6/6 을 되돌리는 가장 작은 값**인 2.5 를 쓴다. 격차를 위해 올린 게 아니다.
export const COUNTER_STRONG = 2.5;
export const COUNTER = (() => {
  const t = new Float32Array(UNIT_KINDS * UNIT_KINDS).fill(1);
  const beats = [
    [U_SPEAR, U_CAV],
    [U_CAV, U_ARCHER], [U_CAV, U_CATA],
    [U_ARCHER, U_SWORD], [U_ARCHER, U_GIANT],
    [U_SWORD, U_SPEAR],
  ];
  for (const [a, d] of beats) t[a * UNIT_KINDS + d] = COUNTER_STRONG;
  return t;
})();

